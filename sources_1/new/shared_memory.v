`timescale 1ns / 1ps

module shared_memory (

    input clk,
    input reset,

    input  [63:0] addr,
    input  [63:0] wdata,
    input         read_en,
    input         write_en,

    output reg [63:0] rdata

);

    // =========================================================
    // 4 KB SHARED MEMORY
    // =========================================================

    reg [31:0] memory [0:1023];

    integer i;

    wire [9:0] word_addr;

    assign word_addr = addr[11:2];


    // =========================================================
    // PROGRAM
    // =========================================================

    initial begin

        // Clear memory
        for (i = 0; i < 1024; i = i + 1)
            memory[i] = 32'h00000000;


        // =====================================================
        // STEP 1
        // x1 = 0x1000
        // IK BASE ADDRESS
        // =====================================================

        memory[0] = 32'h000010B7;


        // =====================================================
        // X = 100
        // =====================================================

        memory[1] = 32'h06400113;

        // SD x2, 0(x1)
        memory[2] = 32'h0020B023;


        // =====================================================
        // Y = 50
        // =====================================================

        memory[3] = 32'h03200113;

        // SD x2, 8(x1)
        memory[4] = 32'h0020B423;


        // =====================================================
        // Z = 50
        // =====================================================

        memory[5] = 32'h03200113;

        // SD x2, 16(x1)
        memory[6] = 32'h0020B823;


        // =====================================================
        // L1 = 100
        // =====================================================

        memory[7] = 32'h06400113;

        // SD x2, 24(x1)
        memory[8] = 32'h0020BC23;


        // =====================================================
        // L2 = 100
        // =====================================================

        memory[9] = 32'h06400113;

        // SD x2, 32(x1)
        memory[10] = 32'h0220B023;


        // =====================================================
        // START IK
        // =====================================================

        memory[11] = 32'h00100113;

        // SD x2, 40(x1)
        memory[12] = 32'h0220B423;


        // =====================================================
        // WAIT
        // =====================================================
        //
        // NOP = ADDI x0,x0,0
        //
        // Give the IK accelerator time to calculate.
        //
        // =====================================================

        memory[13] = 32'h00000013;
        memory[14] = 32'h00000013;
        memory[15] = 32'h00000013;
        memory[16] = 32'h00000013;
        memory[17] = 32'h00000013;
        memory[18] = 32'h00000013;
        memory[19] = 32'h00000013;
        memory[20] = 32'h00000013;
        memory[21] = 32'h00000013;
        memory[22] = 32'h00000013;
        memory[23] = 32'h00000013;
        memory[24] = 32'h00000013;
        memory[25] = 32'h00000013;
        memory[26] = 32'h00000013;
        memory[27] = 32'h00000013;
        memory[28] = 32'h00000013;
        memory[29] = 32'h00000013;
        memory[30] = 32'h00000013;
        memory[31] = 32'h00000013;
        memory[32] = 32'h00000013;
        memory[33] = 32'h00000013;
        memory[34] = 32'h00000013;
        memory[35] = 32'h00000013;
        memory[36] = 32'h00000013;
        memory[37] = 32'h00000013;
        memory[38] = 32'h00000013;
        memory[39] = 32'h00000013;
        memory[40] = 32'h00000013;
        memory[41] = 32'h00000013;
        memory[42] = 32'h00000013;
        memory[43] = 32'h00000013;
        memory[44] = 32'h00000013;
        memory[45] = 32'h00000013;
        memory[46] = 32'h00000013;
        memory[47] = 32'h00000013;
        memory[48] = 32'h00000013;
        memory[49] = 32'h00000013;
        memory[50] = 32'h00000013;
        memory[51] = 32'h00000013;
        memory[52] = 32'h00000013;
        memory[53] = 32'h00000013;
        memory[54] = 32'h00000013;
        memory[55] = 32'h00000013;
        memory[56] = 32'h00000013;
        memory[57] = 32'h00000013;
        memory[58] = 32'h00000013;
        memory[59] = 32'h00000013;
        memory[60] = 32'h00000013;
        memory[61] = 32'h00000013;
        memory[62] = 32'h00000013;
        memory[63] = 32'h00000013;
        memory[64] = 32'h00000013;
        memory[65] = 32'h00000013;
        memory[66] = 32'h00000013;
        memory[67] = 32'h00000013;
        memory[68] = 32'h00000013;
        memory[69] = 32'h00000013;
        memory[70] = 32'h00000013;
        memory[71] = 32'h00000013;
        memory[72] = 32'h00000013;
        memory[73] = 32'h00000013;
        memory[74] = 32'h00000013;
        memory[75] = 32'h00000013;
        memory[76] = 32'h00000013;
        memory[77] = 32'h00000013;
        memory[78] = 32'h00000013;
        memory[79] = 32'h00000013;
        memory[80] = 32'h00000013;
        memory[81] = 32'h00000013;
        memory[82] = 32'h00000013;
        memory[83] = 32'h00000013;
        memory[84] = 32'h00000013;
        memory[85] = 32'h00000013;
        memory[86] = 32'h00000013;
        memory[87] = 32'h00000013;
        memory[88] = 32'h00000013;
        memory[89] = 32'h00000013;
        memory[90] = 32'h00000013;
        memory[91] = 32'h00000013;
        memory[92] = 32'h00000013;
        memory[93] = 32'h00000013;
        memory[94] = 32'h00000013;
        memory[95] = 32'h00000013;
        memory[96] = 32'h00000013;
        memory[97] = 32'h00000013;
        memory[98] = 32'h00000013;
        memory[99] = 32'h00000013;


        // =====================================================
        // x3 = 0x2000
        // PWM BASE ADDRESS
        // =====================================================

        memory[100] = 32'h000021B7;


        // =====================================================
        // READ THETA1
        // =====================================================
        //
        // LD x2, 56(x1)
        // IK theta1 = 0x1038
        //
        // Encoding:
        // 0x0380B103
        //
        // =====================================================

        memory[101] = 32'h0380B103;


        // =====================================================
        // WRITE THETA1 TO PWM1
        // =====================================================
        //
        // SD x2, 0(x3)
        //
        // PWM1 = 0x2000
        //
        // =====================================================

        memory[102] = 32'h0021B023;


        // =====================================================
        // READ THETA2
        // =====================================================
        //
        // LD x2, 64(x1)
        // IK theta2 = 0x1040
        //
        // =====================================================

        memory[103] = 32'h0400B103;


        // =====================================================
        // WRITE THETA2 TO PWM2
        // =====================================================
        //
        // SD x2, 8(x3)
        //
        // =====================================================

        memory[104] = 32'h0021B423;


        // =====================================================
        // READ THETA3
        // =====================================================
        //
        // LD x2, 72(x1)
        // IK theta3 = 0x1048
        //
        // =====================================================

        memory[105] = 32'h0480B103;


        // =====================================================
        // WRITE THETA3 TO PWM3
        // =====================================================
        //
        // SD x2, 16(x3)
        //
        // =====================================================

        memory[106] = 32'h0021B823;


        // =====================================================
        // END
        // =====================================================
        //
        // JAL x0,0
        //
        // =====================================================

        memory[107] = 32'h0000006F;

    end


    // =========================================================
    // 64-BIT WRITE
    // =========================================================

    always @(posedge clk) begin

        if (write_en) begin

            memory[word_addr] <= wdata[31:0];

            memory[word_addr + 1'b1] <= wdata[63:32];

        end

    end


    // =========================================================
    // 64-BIT READ
    // =========================================================

    always @(*) begin

        rdata = 64'h0000000000000000;

        if (read_en) begin

            rdata[31:0] = memory[word_addr];

            rdata[63:32] = memory[word_addr + 1'b1];

        end

    end

endmodule